import { spawnSync } from "node:child_process";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
const lock = JSON.parse(
  readFileSync(new URL("../tools.lock.json", import.meta.url)),
);
const root = new URL("..", import.meta.url).pathname;
const regctl = process.env.REGCTL || "regctl";
function run(command, args, options = {}) {
  const r = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    stdio: "inherit",
    ...options,
  });
  if (r.error) throw r.error;
  if (r.status !== 0) throw Error(command + " failed");
  return r.stdout;
}
run("python3", ["scripts/prepare-image.py"]);
mkdirSync(root + "/.cache", { recursive: true });
run(regctl, [
  "image",
  "copy",
  lock.baseImage,
  "ocidir://.cache/base:alpine",
  "--platform",
  "linux/amd64",
]);
run(regctl, [
  "image",
  "copy",
  "ocidir://.cache/base:alpine",
  "ocidir://.cache/image:recon",
]);
run(regctl, [
  "image",
  "mod",
  "ocidir://.cache/image:recon",
  "--replace",
  "--layer-add",
  "tar=.cache/recon-layer.tar",
  "--config-entrypoint",
  '["/bin/sleep","2147483647"]',
  "--config-cmd",
  "",
  "--config-time",
  "set=2026-11-05T00:00:00Z",
  "--layer-time",
  "set=2026-11-05T00:00:00Z,base-layers=1",
  "--label",
  "org.opencontainers.image.version=" + lock.packVersion,
  "--label",
  "org.opencontainers.image.source=https://github.com/Memrov/PentCloud-tools",
]);
// Normalize the history entry generated by layer-add after its creation.
run(regctl, ["image", "mod", "ocidir://.cache/image:recon", "--replace", "--config-time", "set=2026-11-05T00:00:00Z"]);
const manifest = run(
  regctl,
  ["manifest", "get", "ocidir://.cache/image:recon", "--format", "raw-body"],
  { stdio: ["ignore", "pipe", "inherit"] },
);
const { createHash } = await import("node:crypto");
const digest = "sha256:" + createHash("sha256").update(manifest).digest("hex");
writeFileSync(
  root + "/.cache/image-release.json",
  JSON.stringify(
    {
      packVersion: lock.packVersion,
      digest,
      compressedBytes: JSON.parse(manifest).layers.reduce(
        (n, l) => n + l.size,
        0,
      ),
      platform: lock.platform,
    },
    null,
    2,
  ) + "\n",
);
console.log("Built recon " + lock.packVersion + " " + digest);
